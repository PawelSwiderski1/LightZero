import argparse

from run_mountain_car_corrected_rnd_intrinsic_diagnostic import (
    build_parser as build_diagnostic_parser,
    build_preset_overrides as build_diagnostic_preset_overrides,
)
from run_mountain_car_optimistic_shared_tree import run


def build_parser() -> argparse.ArgumentParser:
    parser = build_diagnostic_parser()
    parser.description = (
        "MountainCar with one mixed-reward MuZero tree and learned one-step "
        "extrinsic-Qstd reward/value heads."
    )
    parser.add_argument("--mixed-reward-beta", type=float, default=1.0)
    parser.add_argument("--qstd-reward-scale", type=float, default=1.0)
    parser.add_argument("--qstd-reward-clip", type=float, default=50.0)
    parser.set_defaults(
        exp_name=(
            "data_ensemble_muzero/"
            "mountain_car_qstd_reward_value_mixed_tree_seed0"
        ),
        max_env_step=45000,
        max_train_iter=15000,
    )
    return parser


def build_preset_overrides(args: argparse.Namespace) -> dict:
    overrides = build_diagnostic_preset_overrides()
    overrides.update(
        intrinsic_reward_source="qstd",
        rnd_exploration=False,
        rnd_intrinsic_reward_weight=0.0,
        rnd_store_collection_rewards=False,
        rnd_use_stored_collection_rewards=False,
        qstd_exploration=True,
        qstd_intrinsic_reward_weight=max(0.0, float(args.mixed_reward_beta)),
        qstd_store_collection_rewards=False,
        # The target for a real replay edge is
        # std_m(reward_m + gamma * value_m(next_latent)).
        qstd_recompute_replay_rewards=True,
        qstd_one_step_include_reward=True,
        qstd_one_step_use_value_calibration=True,
        qstd_reward_scale=max(0.0, float(args.qstd_reward_scale)),
        qstd_reward_clip=(
            None if args.qstd_reward_clip is None else max(0.0, float(args.qstd_reward_clip))
        ),
        qstd_target_snapshot=True,
        qstd_target_snapshot_refresh_per_collect=True,
        qstd_target_inference_batch_size=1024,
        qstd_intrinsic_target_mode="td",
        ensemble_value_calibration=True,
        ensemble_value_calibration_start_phase=1,
        rnd_intrinsic_discount_factor=0.99,
        rnd_intrinsic_td_steps=20,
        intrinsic_value_bootstrap=True,
        # One classic shared tree backs up predicted Qstd prefix rewards and
        # the learned continuation value together with extrinsic return.
        ensemble_search_mode="mean_shared_tree",
        ensemble_ucb_beta=0.0,
        depth_normalized_backup_disagreement=False,
        mixed_reward_tree=True,
        separate_intrinsic_tree=False,
        collection_policy_mode="normal",
        main_tree_policy_prior_mode="learned",
        main_tree_force_root_action_coverage=True,
        intrinsic_tree_immediate_reward_weight=1.0,
        intrinsic_tree_leaf_value_source="default",
        intrinsic_tree_leaf_value_weight=1.0,
        intrinsic_tree_leaf_value_clip=None,
        # Both predictions are trained on every trajectory generated by this
        # mixed policy. Intrinsic gradients also shape recurrent latents.
        intrinsic_model_loss_weight=1.0,
        intrinsic_reward_loss_weight=1.0,
        intrinsic_value_loss_weight=1.0,
        intrinsic_train_value_head=True,
        intrinsic_value_train_on_pure_exploration_only=False,
        intrinsic_head_only=False,
        intrinsic_learning_rate=1e-4,
        intrinsic_reward_target_clip=50.0,
        intrinsic_value_target_clip=500.0,
        intrinsic_tree_pure_exploration_episodes=False,
        pure_exploration_episode_fraction=0.0,
        intrinsic_episode_replay=False,
        save_intrinsic_episode_trajectories=False,
        root_action_diagnostics=True,
        collection_root_action_diagnostics=True,
        fixed_sequence_intrinsic_diagnostics=False,
        main_tree_trace_diagnostics=True,
        main_tree_trace_min_train_iter=0,
        main_tree_trace_max_per_train_iter=8,
        main_tree_trace_max_depth=6,
        main_tree_trace_max_nodes=192,
        main_tree_trace_min_q_std=0.0,
    )
    return overrides


def main() -> None:
    args = build_parser().parse_args()
    run(args, preset_overrides=build_preset_overrides(args))


if __name__ == "__main__":
    main()
