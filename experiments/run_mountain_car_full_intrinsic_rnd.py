import argparse

from run_mountain_car_corrected_rnd_intrinsic_diagnostic import (
    build_parser as build_diagnostic_parser,
    build_preset_overrides as build_diagnostic_preset_overrides,
)
from run_mountain_car_optimistic_shared_tree import run


def build_parser() -> argparse.ArgumentParser:
    parser = build_diagnostic_parser()
    parser.description = (
        "Intrinsic-first MountainCar: every action and training target comes from "
        "a learned-policy RND MuZero agent, with no extrinsic reward/value objective."
    )
    parser.add_argument("--intrinsic-tree-num-simulations", type=int, default=25)
    parser.add_argument("--intrinsic-learning-rate", type=float, default=1e-4)
    parser.add_argument("--rnd-initialization-seed", type=int, default=None)
    parser.set_defaults(
        exp_name="data_ensemble_muzero/mountain_car_full_intrinsic_rnd_seed0",
        max_env_step=45000,
        max_train_iter=15000,
        ensemble_ucb_beta=0.0,
        main_tree_trace_diagnostics=False,
    )
    return parser


def build_preset_overrides(args: argparse.Namespace) -> dict:
    overrides = build_diagnostic_preset_overrides()
    overrides.update(
        # One MuZero optimizer jointly trains the intrinsic MCTS policy, latent
        # consistency, intrinsic reward/value heads, and shared world model.
        # Extrinsic reward/value heads receive no objective.
        intrinsic_only_training=True,
        reward_loss_weight=0.0,
        value_loss_weight=0.0,
        policy_loss_weight=1.0,
        ensemble_search_mode="mean_shared_tree",
        ensemble_ucb_beta=0.0,
        ensemble_eval_search_mode="mean_shared_tree",
        ensemble_eval_ucb_beta=0.0,
        reanalyze_ratio=0.0,
        reanalyze_use_search_value_target=False,
        value_target_mode="td",
        use_priority=False,
        elite_replay=False,
        # Every environment step is selected by the intrinsic tree. Its normal
        # learned policy prior is trained from the stored intrinsic visit policy.
        rnd_intrinsic_reward_weight=1.0,
        separate_intrinsic_tree=True,
        collection_policy_mode="intrinsic_tree_only",
        intrinsic_tree_num_simulations=max(1, int(args.intrinsic_tree_num_simulations)),
        intrinsic_tree_add_exploration_noise=True,
        intrinsic_tree_prior_mode="learned",
        intrinsic_tree_force_root_action_coverage=False,
        intrinsic_tree_pure_exploration_episodes=False,
        intrinsic_tree_store_final_policy=True,
        intrinsic_tree_eval=True,
        intrinsic_tree_normalize_q=True,
        intrinsic_tree_immediate_reward_weight=1.0,
        intrinsic_tree_leaf_value_source="intrinsic_value",
        intrinsic_tree_leaf_value_weight=1.0,
        intrinsic_tree_leaf_value_clip=None,
        # All replay is generated by this policy. Monte Carlo current-snapshot
        # RND returns propagate each discovered region through its full trajectory.
        rnd_intrinsic_target_mode="monte_carlo",
        rnd_intrinsic_td_steps=200,
        rnd_intrinsic_bootstrap=False,
        rnd_target_snapshot_refresh_after_fresh_update=True,
        # Isolate RND initialization so optional auxiliary modules do not change
        # the novelty function for the same experiment seed.
        rnd_initialization_seed=(
            int(args.rnd_initialization_seed)
            if args.rnd_initialization_seed is not None
            else 100000 + int(args.seed)
        ),
        intrinsic_value_bootstrap=False,
        intrinsic_value_train_on_pure_exploration_only=False,
        intrinsic_episode_replay=True,
        intrinsic_episode_buffer_size=20,
        intrinsic_episode_sample_ratio=0.25,
        intrinsic_episode_peak_window_before=200,
        intrinsic_episode_max_age_phases=0,
        # Intrinsic reward/value gradients own the representation and dynamics.
        intrinsic_model_loss_weight=1.0,
        intrinsic_reward_loss_weight=1.0,
        intrinsic_value_loss_weight=1.0,
        intrinsic_train_value_head=True,
        intrinsic_learning_rate=max(1e-8, float(args.intrinsic_learning_rate)),
        intrinsic_head_only=False,
        main_tree_trace_diagnostics=False,
        intrinsic_tree_trace_diagnostics=True,
        intrinsic_tree_trace_best_action=-1,
        intrinsic_tree_trace_min_train_iter=0,
        intrinsic_tree_trace_max_per_train_iter=4,
        intrinsic_tree_trace_max_depth=6,
        intrinsic_tree_trace_max_nodes=192,
    )
    return overrides


def main() -> None:
    args = build_parser().parse_args()
    run(args, preset_overrides=build_preset_overrides(args))


if __name__ == "__main__":
    main()
